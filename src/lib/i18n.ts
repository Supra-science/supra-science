/**
 * Human status label. Arabic uses the dictionary above and falls back to
 * the raw status with underscores as spaces; English Title-Cases the raw
 * status (underscores as spaces).
 */
export function statusLabel(status: string, lang: Lang): string {
  if (lang === "ar") return STATUS_AR[status] ?? status.replace(/_/g, " ");
  return status.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}
